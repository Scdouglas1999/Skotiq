/// Markdown science-report exporter.
///
/// Produces a single self-contained markdown document for one session that
/// captures everything an astronomer would want to share with collaborators
/// or paste into a sky-cloud forum post:
///   * Session header (target, dates, duration, integration)
///   * Frame counts (light/dark/flat/bias, accepted vs rejected)
///   * Photometric snapshot (latest ZP + mean ZP + spread, limiting mag,
///     catalog used, comparison-frame count)
///   * Transparency snapshot (latest, range, dominant bucket)
///   * Field quality (FWHM, eccentricity, uniformity, top-3 issues)
///   * Per-filter integration breakdown
///   * Any moving-object candidates flagged tonight
///
/// The file lands in the exports folder ([resolveSkotiqExportsDirectory]) as
/// `science_report_session_<sessionId>_<timestamp>.md`, on the machine that
/// asked for it: a linked client asks its host for the text and saves it here
/// the same way. We never
/// silently truncate; if a section has no data, it's emitted explicitly
/// (e.g. "No photometric calibration produced this session.") so the
/// recipient can tell the difference between "we ran nothing" and "we
/// produced nothing because conditions were bad".
class ScienceReportExporter {
  final ImagesDao _imagesDao;
  final ScienceDao _scienceDao;
  final SessionsDao _sessionsDao;
  final TargetsDao _targetsDao;

  /// Attribution line in the report footer. The provider passes
  /// `appVersionLabelProvider` so the version tracks version.yaml.
  final String _softwareLabel;

  const ScienceReportExporter({
    required ImagesDao imagesDao,
    required ScienceDao scienceDao,
    required SessionsDao sessionsDao,
    required TargetsDao targetsDao,
    String softwareLabel = 'Skotiq',
  }) : _imagesDao = imagesDao,
       _scienceDao = scienceDao,
       _sessionsDao = sessionsDao,
       _targetsDao = targetsDao,
       _softwareLabel = softwareLabel;

  /// Build a markdown string for [sessionId]. Public so callers can ship
  /// the report somewhere other than disk (Slack DM, email, etc.) without
  /// going through `exportToDisk`.
  ///
  /// [period] is the period search the operator ran on the Science tab. It is
  /// UI state, not a stored product, so the caller passes it; null prints
  /// "Not run for this session".
  Future<String> buildMarkdown(int sessionId, {PeriodFinding? period}) async {
    final session = await _sessionsDao.getSessionById(sessionId);
    if (session == null) {
      throw StateError('Session $sessionId not found');
    }
    DbTarget? target;
    if (session.targetId != null) {
      target = await _targetsDao.getTargetById(session.targetId!);
    }
    final images = await _imagesDao.getImagesForSession(sessionId);
    final calibrations = await _scienceDao.getCalibrationsForSession(sessionId);
    final transparency = await _scienceDao.getTransparencyForSession(sessionId);
    final frameMetrics = await _scienceDao.getFrameQualityMetricsForSession(
      sessionId,
    );
    final movingObjects = await _scienceDao.getMovingObjectsForSession(
      sessionId,
    );
    final photometry = await _scienceDao.getPhotometryForSession(sessionId);

    final b = StringBuffer();
    b.writeln('# Skotiq Science Report — Session #$sessionId');
    b.writeln();
    b.writeln(_sessionHeader(session, target));
    b.writeln();
    b.writeln(_frameCounts(images));
    b.writeln();
    b.writeln(_lightCurveSnapshot(photometry));
    b.writeln();
    b.writeln(_periodAnalysis(period));
    b.writeln();
    b.writeln(_photometrySnapshot(calibrations));
    b.writeln();
    b.writeln(_transparencySnapshot(transparency));
    b.writeln();
    b.writeln(_fieldQuality(frameMetrics));
    b.writeln();
    b.writeln(_filterBreakdown(images));
    b.writeln();
    b.writeln(_movingObjectCandidates(movingObjects));
    b.writeln();
    b.writeln('---');
    b.writeln(
      '_Generated by $_softwareLabel on ${DateTime.now().toUtc().toIso8601String()}._',
    );
    return b.toString();
  }

  /// Write the report to the exports folder and return the file.
  Future<File> exportToDisk(int sessionId, {PeriodFinding? period}) async =>
      save(await buildMarkdown(sessionId, period: period), sessionId);

  /// Write [markdown], the report of [sessionId], into the exports folder.
  /// The returned [File] is flushed, so another app can open it at once.
  static Future<File> save(
    String markdown,
    int sessionId, {
    Future<Directory> Function() exports = resolveSkotiqExportsDirectory,
  }) async {
    // Filesystem-safe on Windows and macOS.
    final stamp = DateTime.now().toUtc().toIso8601String().replaceAll(
      RegExp(r'[:.]'),
      '-',
    );
    final file = File(
      p.join(
        (await exports()).path,
        'science_report_session_${sessionId}_$stamp.md',
      ),
    );
    await file.writeAsString(markdown, flush: true);
    return file;
  }

  /// One convention for every instant the report prints: UTC, with the Z.
  static String _utcStamp(DateTime when) => when.toUtc().toIso8601String();

  String _sessionHeader(ImagingSession session, DbTarget? target) {
    final lines = <String>[
      '## Session',
      '- **Target:** ${target?.name ?? '(no target bound)'}',
      if (target?.constellation != null && target!.constellation!.isNotEmpty)
        '- **Constellation:** ${target.constellation}',
      // UTC with the Z suffix, like the light-curve block and the footer.
      // Drift hands these back as LOCAL DateTimes, so printing them raw
      // produced an ISO-8601-shaped string with no offset and no Z sitting a
      // few lines above a labelled UTC one — a report shared with the AAVSO or
      // the MPC that is ambiguous by up to a day to whoever reads it.
      '- **Started (UTC):** ${_utcStamp(session.startTime)}',
      if (session.endTime != null)
        '- **Ended (UTC):** ${_utcStamp(session.endTime!)}',
      if (session.endTime != null)
        '- **Wall-clock:** ${DurationFormat.of(session.endTime!.difference(session.startTime))}',
    ];
    return lines.join('\n');
  }

  String _frameCounts(List<DbCapturedImage> images) {
    final lights = images.where((i) => i.isLight).toList(growable: false);
    final accepted = lights.where((i) => i.isAccepted).length;
    final integrationSeconds = lights
        .where((i) => i.isAccepted)
        .map((i) => i.exposureDuration)
        .fold<double>(0.0, (acc, v) => acc + v);
    final solved = lights.where((i) => i.isPlateSolved).length;
    return '## Frames\n'
        '| Frame type | Total | Accepted | Plate-solved |\n'
        '| --- | ---: | ---: | ---: |\n'
        '| Light | ${lights.length} | $accepted | $solved |\n'
        '| Dark | ${_countOf(images, FrameType.dark)} | — | — |\n'
        '| Flat | ${_countOf(images, FrameType.flat)} | — | — |\n'
        '| Bias | ${_countOf(images, FrameType.bias)} | — | — |\n'
        '\n'
        '**Accepted integration time:** ${DurationFormat.of(Duration(seconds: integrationSeconds.round()))}.';
  }

  int _countOf(List<DbCapturedImage> images, FrameType type) =>
      images.where((i) => i.recordedFrameType == type).length;

  String _photometrySnapshot(
    List<FramePhotometricCalibrationRow> calibrations,
  ) {
    final calibrated = calibrations
        .where(
          (c) => c.isCalibrated && c.zeroPoint != null && c.zeroPoint!.isFinite,
        )
        .toList(growable: false);
    if (calibrated.isEmpty) {
      return '## Photometric calibration\n'
          'No photometric calibration produced this session. This usually means '
          'too few frames solved against the catalog (need ≥ 5–10 calibrated '
          'frames before a transparency model stabilizes).';
    }
    final zps = calibrated.map((c) => c.zeroPoint!).toList()..sort();
    final median = zps[zps.length ~/ 2];
    final mean = zps.reduce((a, b) => a + b) / zps.length;
    final range = zps.last - zps.first;
    final latest = calibrated.last;
    final lim5 =
        calibrated
            .map((c) => c.limitingMag5Sigma)
            .whereType<double>()
            .where((v) => v.isFinite)
            .toList()
          ..sort();
    final limStr = lim5.isEmpty
        ? '—'
        : 'median ${lim5[lim5.length ~/ 2].toStringAsFixed(2)} mag';
    final catalogs = calibrated.map((c) => c.catalogSource).toSet().toList();
    return '## Photometric calibration\n'
        '- **Latest zero point:** ${latest.zeroPoint!.toStringAsFixed(2)} mag '
        '(${latest.matchedStarCount} catalog stars matched, RMS '
        '${latest.calibrationRms.toStringAsFixed(3)})\n'
        '- **Median ZP across ${calibrated.length} frames:** ${median.toStringAsFixed(2)} mag '
        '(mean ${mean.toStringAsFixed(2)}, range ${range.toStringAsFixed(2)} mag)\n'
        '- **Limiting magnitude (5σ):** $limStr\n'
        '- **Catalog source${catalogs.length == 1 ? '' : 's'}:** '
        '${catalogs.join(', ')}\n';
  }

  /// The differential-photometry time series this session actually produced.
  ///
  /// Read from `photometry_measurements`, so the light curve — the product of
  /// a variable-star run — is in the report rather than represented by the
  /// calibration section's absence.
  String _lightCurveSnapshot(List<PhotometryMeasurementRow> rows) {
    if (rows.isEmpty) {
      return '## Light curve\n'
          'No photometry measurements were recorded for this session. Live '
          'reduction has to be enabled on the capture (Science Photometry '
          'node, or Science → live reduction) for a light curve to exist.';
    }
    final targets = rows
        .where((r) => r.role == 'target')
        .toList(growable: false);
    final comparisons =
        rows
            .where((r) => r.role != 'target')
            .map((r) => r.objectId)
            .toSet()
            .toList(growable: false)
          ..sort();
    final series = targets.isEmpty ? rows : targets;
    final objectIds = series.map((r) => r.objectId).toSet().toList()..sort();
    final first = series.first.timestamp.toUtc();
    final last = series.last.timestamp.toUtc();

    final diffs = series
        .map((r) => r.differentialMagnitude)
        .whereType<double>()
        .where((v) => v.isFinite)
        .toList(growable: false);
    final String diffLine;
    if (diffs.isEmpty) {
      diffLine =
          '- **Differential magnitude:** not computed (no comparison stars '
          'resolved)\n';
    } else {
      final mean = diffs.reduce((a, b) => a + b) / diffs.length;
      final variance =
          diffs.map((v) => (v - mean) * (v - mean)).reduce((a, b) => a + b) /
          diffs.length;
      final rms = math.sqrt(variance);
      diffLine =
          '- **Differential magnitude:** mean ${mean.toStringAsFixed(4)}, '
          'RMS ${rms.toStringAsFixed(4)} mag over ${diffs.length} points\n';
    }

    final outliers = series.where((r) => r.isOutlier).length;
    return '## Light curve\n'
        '- **Points:** ${series.length}'
        '${outliers > 0 ? ' ($outliers flagged as outliers)' : ''}\n'
        '- **Target object:** ${objectIds.join(', ')}\n'
        '- **Comparison stars:** '
        '${comparisons.isEmpty ? 'none' : comparisons.join(', ')}\n'
        '- **First / last measurement (UTC):** '
        '${first.toIso8601String()} → ${last.toIso8601String()}\n'
        '$diffLine';
  }

  /// The period search the operator ran, or an explicit statement that none was.
  String _periodAnalysis(PeriodFinding? period) {
    if (period == null) {
      return '## Period analysis\n'
          'Not run for this session.';
    }
    final cycles = period.observedCycles.toStringAsFixed(1);
    final constrained = period.isPeriodConstrained
        ? '$cycles cycles observed'
        : 'UNCONSTRAINED — only $cycles cycles '
              'fit in the baseline, so this is a lower bound, not a measurement';
    return '## Period analysis\n'
        '- **Lomb-Scargle best period:** '
        '${period.lombScarglePeriodDays.toStringAsFixed(6)} d '
        '(peak power ${period.peakPower.toStringAsFixed(3)}, '
        'FAP ${period.falseAlarmProbability.toStringAsExponential(2)})\n'
        '- **Baseline / coverage:** ${period.baselineDays.toStringAsFixed(4)} d, '
        '$constrained\n'
        '- **Searched range:** '
        '${period.searchedMinPeriodDays.toStringAsFixed(4)} – '
        '${period.searchedMaxPeriodDays.toStringAsFixed(4)} d\n'
        '- **BLS best period:** ${period.blsPeriodDays.toStringAsFixed(6)} d '
        '(depth ${period.transitDepthMag.toStringAsFixed(4)} mag, duration '
        '${period.transitDurationDays.toStringAsFixed(4)} d, '
        'SDE ${period.signalDetectionEfficiency.toStringAsFixed(2)})\n';
  }

  String _transparencySnapshot(List<TransparencySampleRow> samples) {
    if (samples.isEmpty) {
      return '## Transparency\n'
          'No transparency samples produced. A transparency estimate needs '
          'at least 5 calibrated frames to stabilize — likely few frames '
          'reached calibration tonight.';
    }
    final values = samples
        .map((s) => s.transparencyPercent)
        .toList(growable: false);
    final mean = values.reduce((a, b) => a + b) / values.length;
    final minV = values.reduce(math.min);
    final maxV = values.reduce(math.max);
    final latest = samples.last;
    final buckets = <String, int>{};
    for (final s in samples) {
      buckets[s.qualityBucket] = (buckets[s.qualityBucket] ?? 0) + 1;
    }
    final dominant = buckets.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    return '## Transparency\n'
        '- **Latest:** ${latest.transparencyPercent.toStringAsFixed(0)}% '
        '(${latest.qualityBucket})\n'
        '- **Mean / range:** ${mean.toStringAsFixed(0)}% '
        '(${minV.toStringAsFixed(0)}% – ${maxV.toStringAsFixed(0)}%)\n'
        '- **Dominant bucket:** ${dominant.first.key} (${dominant.first.value} of ${samples.length} samples)\n';
  }

  String _fieldQuality(List<ScienceFrameQualityMetricsRow> metrics) {
    if (metrics.isEmpty) {
      return '## Field quality\n'
          'No frame-quality metrics produced. Either frame-quality maps are '
          'disabled in settings or no eligible light frames reached the '
          'pipeline.';
    }
    final latest = metrics.last;
    final allCv = metrics.map((m) => m.uniformityCv).toList(growable: false);
    final meanCv = allCv.reduce((a, b) => a + b) / allCv.length;
    final clipFrames = metrics
        .where((m) => m.highClipPercent > 0.5 || m.lowClipPercent > 0.5)
        .length;
    return '## Field quality\n'
        '- **Latest frame:** background ${latest.background.toStringAsFixed(0)} ADU, '
        '${latest.snr > 0 ? 'sky noise ${latest.snr.toStringAsFixed(1)}x the read noise, ' : ''}'
        'uniformity CV '
        '${latest.uniformityCv.toStringAsFixed(3)}\n'
        '- **Mean uniformity CV across session:** ${meanCv.toStringAsFixed(3)} '
        '(>0.28 is a gradient warning)\n'
        '- **Frames with clipping:** $clipFrames of ${metrics.length}\n';
  }

  String _filterBreakdown(List<DbCapturedImage> images) {
    final perFilter = <String, ({int frames, double seconds})>{};
    for (final image in images) {
      if (!image.isLight || !image.isAccepted) {
        continue;
      }
      final filter = (image.filter ?? '').isEmpty
          ? '(no filter)'
          : image.filter!;
      final existing = perFilter[filter] ?? (frames: 0, seconds: 0.0);
      perFilter[filter] = (
        frames: existing.frames + 1,
        seconds: existing.seconds + image.exposureDuration,
      );
    }
    if (perFilter.isEmpty) {
      return '## Filter breakdown\n'
          'No accepted light frames to break out.';
    }
    final rows = perFilter.entries
        .map((entry) {
          return '| ${entry.key} | ${entry.value.frames} | ${DurationFormat.of(Duration(seconds: entry.value.seconds.round()))} |';
        })
        .join('\n');
    return '## Filter breakdown\n'
        '| Filter | Frames | Integration |\n'
        '| --- | ---: | ---: |\n$rows';
  }

  String _movingObjectCandidates(List<MovingObjectCandidateRow> rows) {
    if (rows.isEmpty) {
      return '## Moving objects\n'
          'No candidates flagged tonight.';
    }
    final lines = StringBuffer('## Moving objects\n');
    lines.writeln(
      '| Candidate | RA (deg) | Dec (deg) | Motion ("/min) | Confidence |',
    );
    lines.writeln('| --- | ---: | ---: | ---: | ---: |');
    for (final r in rows) {
      lines.writeln(
        '| ${r.objectName ?? r.candidateId} | ${r.raDegrees.toStringAsFixed(4)} | ${r.decDegrees.toStringAsFixed(4)} | ${r.motionArcsecPerMinute.toStringAsFixed(2)} | ${(r.confidence * 100).toStringAsFixed(0)}% |',
      );
    }
    return lines.toString();
  }
}
