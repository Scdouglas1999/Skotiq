class _Baseline {
  _Baseline(this._doc);

  final Map<String, dynamic> _doc;

  static const _sections = {
    _Rule.backendClass: 'backendClass',
    _Rule.srcImport: 'srcImport',
    _Rule.nodeDispatch: 'nodeDispatch',
    _Rule.coreLayers: 'coreLayers',
  };

  static _Baseline load(String path) {
    final file = File(path);
    if (!file.existsSync()) {
      stderr.writeln('Baseline not found: $path');
      exit(2);
    }
    final decoded = jsonDecode(file.readAsStringSync());
    if (decoded is! Map<String, dynamic>) {
      stderr.writeln('Baseline $path is not a JSON object.');
      exit(2);
    }
    return _Baseline(decoded);
  }

  Map<String, dynamic> _allowed(_Rule rule) {
    final section = _doc[_sections[rule]];
    if (section is! Map<String, dynamic>) return {};
    final allowed = section['allowed'];
    return allowed is Map<String, dynamic> ? allowed : {};
  }

  Map<String, int> counts(_Rule rule) => {
    for (final MapEntry(key: key, value: value) in _allowed(rule).entries)
      key: _countOf(value),
  };

  int count(_Rule rule, String key) => _countOf(_allowed(rule)[key]);

  static int _countOf(Object? value) => switch (value) {
    int n => n,
    {'count': int n} => n,
    _ => 0,
  };

  void shrinkTo(Map<_Rule, Map<String, int>> current) {
    for (final rule in _Rule.counted) {
      final allowed = _allowed(rule);
      for (final key in allowed.keys.toList()) {
        final now = current[rule]![key] ?? 0;
        final was = _countOf(allowed[key]);
        if (now == 0) {
          allowed.remove(key);
        } else if (now < was) {
          final value = allowed[key];
          allowed[key] = value is Map<String, dynamic>
              ? {...value, 'count': now}
              : now;
        }
      }
    }
  }

  void save(String path) {
    File(path).writeAsStringSync(
      '${const JsonEncoder.withIndent('  ').convert(_doc)}\n',
    );
  }
}
