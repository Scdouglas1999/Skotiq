// Enclosing declarations (baseline keys)

const _statementWords = {
  'if',
  'else',
  'for',
  'while',
  'do',
  'switch',
  'case',
  'return',
  'await',
  'yield',
  'throw',
  'catch',
  'try',
  'assert',
  'new',
  'final',
  'var',
  'const',
};

final _dartMember = RegExp(
  r'^(?:@\w+\s+)?(?:(?:static|external|factory|abstract|covariant|late)\s+)*'
  r'([A-Za-z_][\w<>?,\[\]. ]*?)\s+(?:(?:get|set|operator)\s+)?'
  r'([A-Za-z_]\w*)\s*(?:<[^()]*>)?\s*(?:\(|\{|=>)',
);
final _dartGetter = RegExp(
  r'^(?:static\s+)?(?:[\w<>?,\[\]. ]+\s+)?get\s+(\w+)',
);
final _dartVariable = RegExp(
  r'^(?:static\s+)?(?:final|const|late|var)\s+(?:[\w<>?,\[\]. ]+\s+)?([A-Za-z_]\w*)\s*=',
);
final _dartType = RegExp(
  r'^(?:abstract\s+|sealed\s+|final\s+|base\s+|interface\s+|mixin\s+)*'
  r'(?:class|mixin|extension|enum|extension\s+type)\s+(\w+)',
);

/// The lines that open the blocks around [line], innermost first, found by
/// indentation. A line that starts with `)`, `]` or `}` closes a multi-line
/// signature or an `else`; the line that opened it at the same indentation
/// stands in for it.
List<String> _enclosingLines(List<String> lines, int line) {
  final out = <String>[];
  var indent = _indent(lines[line]);
  var closer = false;
  for (var i = line - 1; i >= 0 && (indent > 0 || closer); i--) {
    final trimmed = lines[i].trim();
    if (trimmed.isEmpty) continue;
    final ind = _indent(lines[i]);
    if (ind > indent || (ind == indent && !closer)) continue;
    indent = ind;
    closer = RegExp(r'^[)\]}]').hasMatch(trimmed);
    if (!closer) out.add(trimmed);
  }
  return out;
}

/// `Type.member` for the class-level member (or top-level declaration) that
/// holds [line].
String _dartEnclosing(List<String> lines, int line) {
  final enclosing = _enclosingLines(lines, line);
  final typeIndex = enclosing.indexWhere(_dartType.hasMatch);
  final type = typeIndex < 0
      ? null
      : _dartType.firstMatch(enclosing[typeIndex])!.group(1);
  final memberLine = typeIndex > 0
      ? enclosing[typeIndex - 1]
      : typeIndex < 0 && enclosing.isNotEmpty
      ? enclosing.last
      : null;
  final member =
      (memberLine == null ? null : _dartMemberName(memberLine)) ??
      _dartMemberName(lines[line].trim(), variables: false) ??
      'top';
  return type == null ? member : '$type.$member';
}

String? _dartMemberName(String trimmed, {bool variables = true}) {
  final variable = variables ? _dartVariable.firstMatch(trimmed) : null;
  if (variable != null) return variable.group(1);
  final getter = _dartGetter.firstMatch(trimmed);
  if (getter != null &&
      !_statementWords.contains(trimmed.split(RegExp(r'\s')).first)) {
    return getter.group(1);
  }
  final m = _dartMember.firstMatch(trimmed);
  if (m == null) return null;
  final first = m.group(1)!.split(RegExp(r'[\s<]')).first;
  if (_statementWords.contains(first) || _statementWords.contains(m.group(2))) {
    return null;
  }
  return m.group(2);
}

/// `Impl::fn` (or `fn`) for the function that holds [line].
String _rustEnclosing(List<String> lines, int line) {
  final fn = RegExp(r'\bfn\s+(\w+)');
  final impl = RegExp(r'^impl\b(?:<[^>]*>)?\s+(?:[\w:<>, ]+\s+for\s+)?(\w+)');
  final enclosing = _enclosingLines(lines, line);
  final fnIndex = enclosing.lastIndexWhere(fn.hasMatch);
  if (fnIndex < 0) return 'top';
  final name = fn.firstMatch(enclosing[fnIndex])!.group(1);
  for (final text in enclosing.skip(fnIndex + 1)) {
    final m = impl.firstMatch(text);
    if (m != null) return '${m.group(1)}::$name';
  }
  return name!;
}

