/// Package name -> package directory, for `apps/*` and `packages/*`.
Map<String, String> _findDartPackages() {
  final out = <String, String>{};
  for (final root in const ['apps', 'packages']) {
    final dir = Directory(root);
    if (!dir.existsSync()) continue;
    for (final entity in dir.listSync()) {
      if (entity is! Directory) continue;
      final pubspec = File('${entity.path}/pubspec.yaml');
      if (!pubspec.existsSync()) continue;
      final name = _yamlName(pubspec.readAsLinesSync());
      if (name != null) out[name] = _norm(entity.path);
    }
  }
  return out;
}

String? _yamlName(List<String> lines) {
  for (final line in lines) {
    final m = RegExp(r'^name:\s*([\w]+)').firstMatch(line);
    if (m != null) return m.group(1);
  }
  return null;
}

/// Dependency name -> pubspec line, from `dependencies` and
/// `dev_dependencies`.
Map<String, int> _pubspecDependencies(List<String> lines) {
  final out = <String, int>{};
  var inDeps = false;
  for (var i = 0; i < lines.length; i++) {
    final line = lines[i];
    if (RegExp(r'^\S').hasMatch(line)) {
      inDeps = RegExp(r'^(dependencies|dev_dependencies):').hasMatch(line);
      continue;
    }
    if (!inDeps) continue;
    final m = RegExp(r'^  ([a-z_][a-z0-9_]*):').firstMatch(line);
    if (m != null) out[m.group(1)!] = i + 1;
  }
  return out;
}

String? _packageOf(String path, Map<String, String> packages) {
  String? best;
  var bestLength = -1;
  for (final MapEntry(key: name, value: dir) in packages.entries) {
    if (path.startsWith('$dir/') && dir.length > bestLength) {
      best = name;
      bestLength = dir.length;
    }
  }
  return best;
}

final _packageImport = RegExp(
  r'''^\s*(?:import|export)\s+['"]package:([a-z_][a-z0-9_]*)/([^'"]*)['"]''',
);
final _flutterImport = RegExp(
  r'''^\s*(?:import|export)\s+['"](?:package:flutter/|dart:ui['"])''',
);

List<_Violation> _checkDartDirection(
  Map<String, String> packages,
  List<String> files,
) {
  final out = <_Violation>[];
  final workspace = {...packages.keys, ..._externalWorkspacePackages};
  for (final MapEntry(key: name, value: dir) in packages.entries) {
    final rule = _dartPackages[name];
    if (rule == null) {
      out.add(
        _Violation(
          _Rule.packageDirection,
          '$dir/pubspec.yaml',
          'package $name has no row in the layering table',
          'Add $name to _dartPackages in '
              'tools/production/architecture_rules_audit.dart with the '
              'packages below it that it may use.',
        ),
      );
      continue;
    }
    final deps = _pubspecDependencies(
      File('$dir/pubspec.yaml').readAsLinesSync(),
    );
    for (final MapEntry(key: dep, value: line) in deps.entries) {
      if (!workspace.contains(dep) || dep == name) continue;
      if (!rule.mayUse.contains(dep)) {
        out.add(_directionViolation('$dir/pubspec.yaml:$line', name, dep));
      }
    }
    if (rule.pureDart && deps.containsKey('flutter')) {
      out.add(
        _Violation(
          _Rule.packageDirection,
          '$dir/pubspec.yaml:${deps['flutter']}',
          '$name is pure Dart and may not depend on Flutter',
          rule.instead,
        ),
      );
    }
  }
  for (final path in files) {
    final name = _packageOf(path, packages);
    if (name == null) continue;
    final rule = _dartPackages[name];
    if (rule == null) continue;
    final lines = _readLines(path);
    final isLib =
        path.startsWith('${packages[name]}/lib/') ||
        path.startsWith('${packages[name]}/bin/');
    for (var i = 0; i < lines.length; i++) {
      final m = _packageImport.firstMatch(lines[i]);
      if (m != null) {
        final dep = m.group(1)!;
        if (workspace.contains(dep) &&
            dep != name &&
            !rule.mayUse.contains(dep)) {
          out.add(_directionViolation('$path:${i + 1}', name, dep));
        }
      }
      if (rule.pureDart && isLib && _flutterImport.hasMatch(lines[i])) {
        out.add(
          _Violation(
            _Rule.packageDirection,
            '$path:${i + 1}',
            '$name is pure Dart and may not import Flutter',
            rule.instead,
          ),
        );
      }
    }
  }
  return out;
}

_Violation _directionViolation(String location, String from, String to) {
  final rule = _dartPackages[from]!;
  final allowed = rule.mayUse.isEmpty
      ? 'no other Skotiq package'
      : (rule.mayUse.toList()..sort()).join(', ');
  return _Violation(
    _Rule.packageDirection,
    location,
    '$from uses $to; $from may use only $allowed',
    [
      if (rule.instead.isNotEmpty) rule.instead,
      'Move the shared code down to a package both may use, or pass the '
          'value in from the layer above.',
    ].join(' '),
  );
}

List<_Violation> _checkRustDirection() {
  final out = <_Violation>[];
  final root = Directory('native/skotiq_native');
  if (!root.existsSync()) return out;
  for (final entity in root.listSync()) {
    if (entity is! Directory) continue;
    final manifest = File('${entity.path}/Cargo.toml');
    if (!manifest.existsSync()) continue;
    final path = _norm(manifest.path);
    final lines = manifest.readAsLinesSync();
    String? name;
    String? section;
    final deps = <String, int>{};
    for (var i = 0; i < lines.length; i++) {
      final line = lines[i].trim();
      final header = RegExp(r'^\[(.+)\]$').firstMatch(line);
      if (header != null) {
        section = header.group(1);
        final table = RegExp(
          r'(?:^|\.)(?:dependencies|dev-dependencies|build-dependencies)\.(skotiq_\w+)$',
        ).firstMatch(section!);
        if (table != null) deps[table.group(1)!] = i + 1;
        continue;
      }
      if (section == 'package') {
        final m = RegExp(r'^name\s*=\s*"([^"]+)"').firstMatch(line);
        if (m != null) name = m.group(1);
      } else if (section != null &&
          RegExp(
            r'(?:^|\.)(?:dependencies|dev-dependencies|build-dependencies)$',
          ).hasMatch(section)) {
        final m = RegExp(r'^(skotiq_\w+)\s*[=.]').firstMatch(line);
        if (m != null) deps[m.group(1)!] = i + 1;
      }
    }
    if (name == null) continue;
    final allowed = _rustCrates[name];
    if (allowed == null) {
      out.add(
        _Violation(
          _Rule.packageDirection,
          path,
          'crate $name has no row in the layering table',
          'Add $name to _rustCrates in '
              'tools/production/architecture_rules_audit.dart with the crates '
              'below it that it may use.',
        ),
      );
      continue;
    }
    for (final MapEntry(key: dep, value: line) in deps.entries) {
      if (dep == name || allowed.contains(dep)) continue;
      final list = allowed.isEmpty
          ? 'no other Skotiq crate'
          : (allowed.toList()..sort()).join(', ');
      out.add(
        _Violation(
          _Rule.packageDirection,
          '$path:$line',
          '$name depends on $dep; $name may use only $list',
          _rustInstead,
        ),
      );
    }
  }
  return out;
}

