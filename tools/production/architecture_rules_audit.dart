/// Architecture rules audit: the structural rules of the codebase that a
/// machine can check, each failure naming where the change belongs instead.
///
/// Rules:
///   package-direction   A Dart package or Rust crate uses only the packages
///                       below it (`_dartPackages`, `_rustCrates`), and
///                       skotiq_astro stays pure Dart.
///   backend-class       Only the backend files test or cast a backend's
///                       class (`is NetworkBackend`, `as FfiBackend`, ...).
///   src-import          No file imports another package's `src/` files.
///   node-dispatch       No new per-node-type dispatch (a switch, `is` chain
///                       or Rust `match` naming [_dispatchThreshold] or more
///                       node types) outside the node table.
///   core-layers         skotiq_core's backend/, database/, models/ and
///                       services/ do not import providers/; a service that
///                       needs a Riverpod Ref is listed in the baseline with
///                       the reason.
///   core-barrels        skotiq_core has one barrel per `lib/src/` directory
///                       and no union of them: a barrel exports only its own
///                       directory, nothing under `src/` re-exports another
///                       layer or imports a barrel, and no import of a core
///                       barrel carries `hide`.
///   app-shared          skotiq_app's shared folders (widgets/, services/,
///                       utils/, tours/, localization/ and the route table
///                       in router/) import no screen and none of the files
///                       that put the app together.
///
/// Sites that existed when a rule was introduced are listed, by count, in the
/// baseline file (`tools/production/architecture_rules_baseline.json`). A key
/// names the package and import (src-import), the layer and file name
/// (core-layers) or the file name and enclosing declaration (the other two),
/// never a line number, so moving code does not touch the baseline. Only a
/// count above the baseline fails.
///
/// Usage (from the repository root):
///   dart run tools/production/architecture_rules_audit.dart
///       [--baseline <file>] [--scope <audit-scope.yaml>] [--sync-baseline]
///       [--list-sites]
///
/// `--list-sites` prints every counted site (location -> baseline key) as
/// JSON and exits, for reviewing the baseline.
///
/// `--sync-baseline` lowers counts to what the tree still has and drops
/// entries that are gone. It never adds an entry: a new allowed site is a
/// hand edit with a reason.
///
/// Exit code: 0 clean, 1 violations, 2 configuration error.
