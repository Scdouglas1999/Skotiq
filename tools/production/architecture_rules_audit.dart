// Source helpers

/// [source] with comments and string contents replaced by spaces, newlines
/// kept, so offsets and line numbers still match the file.
String _blankDart(String source) {
  final out = StringBuffer();
  var i = 0;
  final n = source.length;
  void blank(int end) {
    for (; i < end && i < n; i++) {
      out.write(source[i] == '\n' ? '\n' : ' ');
    }
  }

  while (i < n) {
    final c = source[i];
    final next = i + 1 < n ? source[i + 1] : '';
    if (c == '/' && next == '/') {
      final end = source.indexOf('\n', i);
      blank(end < 0 ? n : end);
    } else if (c == '/' && next == '*') {
      var depth = 0;
      var j = i;
      while (j < n) {
        if (source.startsWith('/*', j)) {
          depth++;
          j += 2;
        } else if (source.startsWith('*/', j)) {
          depth--;
          j += 2;
          if (depth == 0) break;
        } else {
          j++;
        }
      }
      blank(j);
    } else if (c == '\'' || c == '"') {
      final raw = i > 0 && source[i - 1] == 'r';
      final quote = source.startsWith('$c$c$c', i) ? '$c$c$c' : c;
      var close = i + quote.length;
      while (close < n &&
          !source.startsWith(quote, close) &&
          (quote.length == 3 || source[close] != '\n')) {
        close += !raw && source[close] == '\\' ? 2 : 1;
      }
      out.write(quote);
      i += quote.length;
      blank(close);
      if (source.startsWith(quote, i)) {
        out.write(quote);
        i += quote.length;
      }
    } else {
      out.write(c);
      i++;
    }
  }
  return out.toString();
}

/// Rust: comments and string literals blanked (lifetimes and char literals
/// are left alone; neither holds a brace that matters here except `'{'`).
String _blankRust(String source) {
  final out = StringBuffer();
  var i = 0;
  final n = source.length;
  void blank(int end) {
    for (; i < end && i < n; i++) {
      out.write(source[i] == '\n' ? '\n' : ' ');
    }
  }

  while (i < n) {
    final c = source[i];
    final next = i + 1 < n ? source[i + 1] : '';
    if (c == '/' && next == '/') {
      final end = source.indexOf('\n', i);
      blank(end < 0 ? n : end);
    } else if (c == '/' && next == '*') {
      final end = source.indexOf('*/', i + 2);
      blank(end < 0 ? n : end + 2);
    } else if (c == '\'' &&
        i + 2 < n &&
        (source[i + 2] == '\'' ||
            (source[i + 1] == '\\' && i + 3 < n && source[i + 3] == '\''))) {
      final end = source.indexOf('\'', i + 2) + 1;
      blank(end);
    } else if (c == '"') {
      var j = i + 1;
      while (j < n && source[j] != '"') {
        j += source[j] == '\\' ? 2 : 1;
      }
      blank(j + 1);
    } else {
      out.write(c);
      i++;
    }
  }
  return out.toString();
}

int _lineOf(String text, int offset) {
  var line = 0;
  for (var i = 0; i < offset && i < text.length; i++) {
    if (text.codeUnitAt(i) == 10) line++;
  }
  return line;
}

int _indent(String line) => line.length - line.trimLeft().length;

String _readText(String path) {
  try {
    return File(path).readAsStringSync();
  } on FileSystemException {
    return File(path).readAsStringSync(encoding: latin1);
  } on FormatException {
    return File(path).readAsStringSync(encoding: latin1);
  }
}

List<String> _readLines(String path) => _readText(path).split('\n');

String _basename(String path) => path.substring(path.lastIndexOf('/') + 1);

String _norm(String path) {
  var p = path.replaceAll('\\', '/');
  if (p.startsWith('./')) p = p.substring(2);
  return p;
}

