List<String> _nodeTypeNames() {
  final file = File(_nodeTablePath);
  if (!file.existsSync()) {
    stderr.writeln(
      'Node table not found at $_nodeTablePath. If it moved, update '
      '_nodeTablePath in tools/production/architecture_rules_audit.dart.',
    );
    exit(2);
  }
  final names = RegExp(r'NodeKind<(\w+)>')
      .allMatches(file.readAsStringSync())
      .map((m) => m.group(1)!)
      .where((n) => n != 'N' && n != 'SequenceNode')
      .toSet()
      .toList();
  if (names.length < _dispatchThreshold) {
    stderr.writeln(
      'Read only ${names.length} node types from $_nodeTablePath; the '
      'table\'s shape changed. Update _nodeTypeNames.',
    );
    exit(2);
  }
  return names;
}

List<_Site> _dartDispatchSites(List<String> files) {
  final names = _nodeTypeNames();
  final nameAlternation = names.join('|');
  final anyName = RegExp('\\b($nameAlternation)\\b');
  final isTest = RegExp('\\bis!?\\s+($nameAlternation)\\b');
  // A node type in pattern position: at the start of an arm or after `case`
  // or `||`, followed by `(` or a binding name.
  final casePattern = RegExp(
    '(?:^|\\bcase\\s+|\\|\\|)\\s*($nameAlternation)'
    '(?:\\s*\\(|\\s+[A-Za-z_]\\w*\\s*(?:=>|\\|\\||&&|:|\\bwhen\\b))',
    multiLine: true,
  );
  final out = <_Site>[];
  for (final path in files) {
    if (_nodeTableFiles.contains(path)) continue;
    final source = _readText(path);
    if (!anyName.hasMatch(source)) continue;
    final code = _blankDart(source);
    final lines = code.split('\n');
    final spans = <({int start, int end, int types})>[];
    for (final m in RegExp(r'\bswitch\s*\(').allMatches(code)) {
      final open = _bodyOpen(code, m.end - 1);
      if (open < 0) continue;
      final close = _matchingBrace(code, open);
      final found = casePattern
          .allMatches(code.substring(open, close))
          .map((n) => n.group(1)!)
          .toSet();
      if (found.length < _dispatchThreshold) continue;
      spans.add((start: m.start, end: close, types: found.length));
    }
    // A switch nested in a flagged switch is the same dispatch; report the
    // innermost one, which is where the per-type arms are.
    final innermost = spans.where(
      (s) => !spans.any((o) => o.start > s.start && o.end <= s.end),
    );
    for (final span in innermost) {
      final line = _lineOf(code, span.start);
      out.add(
        _Site(
          '${_basename(path)}::${_dartEnclosing(lines, line)}',
          '$path:${line + 1}',
          'switch over ${span.types} node types',
        ),
      );
    }
    final tests = isTest
        .allMatches(code)
        .where((m) => !spans.any((s) => m.start > s.start && m.start < s.end))
        .toList();
    // A chain is the `is` tests of one declaration with no long gap between
    // them.
    var chain = <({String name, int line})>[];
    String? chainOwner;
    void flush() {
      final distinct = chain.map((t) => t.name).toSet();
      if (distinct.length >= _dispatchThreshold) {
        out.add(
          _Site(
            '${_basename(path)}::$chainOwner',
            '$path:${chain.first.line + 1}',
            '`is` chain over ${distinct.length} node types',
          ),
        );
      }
      chain = [];
    }

    for (final m in tests) {
      final line = _lineOf(code, m.start);
      final owner = _dartEnclosing(lines, line);
      if (chain.isNotEmpty &&
          (owner != chainOwner || line - chain.last.line > _isChainGap)) {
        flush();
      }
      chainOwner = owner;
      chain.add((name: m.group(1)!, line: line));
    }
    flush();
  }
  return out;
}

List<_Site> _rustDispatchSites(List<String> files) {
  final arm = RegExp(
    r'^\s*\|?\s*NodeType::(\w+)\s*(?:\(|\{|=>|\|)',
    multiLine: true,
  );
  final out = <_Site>[];
  for (final path in files) {
    if (_nodeTableFiles.contains(path)) continue;
    final source = _readText(path);
    if (!source.contains('NodeType::')) continue;
    final code = _blankRust(source);
    final lines = code.split('\n');
    for (final m in RegExp(r'\bmatch\b[^{;]*\{').allMatches(code)) {
      final open = m.end - 1;
      final close = _matchingBrace(code, open);
      final found = arm
          .allMatches(code.substring(open, close))
          .map((a) => a.group(1)!)
          .toSet();
      if (found.length < _dispatchThreshold) continue;
      final line = _lineOf(code, m.start);
      out.add(
        _Site(
          '${_basename(path)}::${_rustEnclosing(lines, line)}',
          '$path:${line + 1}',
          'match over ${found.length} NodeType variants',
        ),
      );
    }
  }
  return out;
}

/// The `{` that opens a switch body, given the `(` of its subject.
int _bodyOpen(String code, int paren) {
  var depth = 0;
  for (var i = paren; i < code.length; i++) {
    final c = code[i];
    if (c == '(') depth++;
    if (c == ')') {
      depth--;
      if (depth == 0) {
        for (var j = i + 1; j < code.length; j++) {
          if (code[j] == '{') return j;
          if (code[j].trim().isNotEmpty) return -1;
        }
        return -1;
      }
    }
  }
  return -1;
}

int _matchingBrace(String code, int open) {
  var depth = 0;
  for (var i = open; i < code.length; i++) {
    if (code[i] == '{') depth++;
    if (code[i] == '}') {
      depth--;
      if (depth == 0) return i;
    }
  }
  return code.length;
}

