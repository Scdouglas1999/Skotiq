void main(List<String> args) {
  final scope = AuditScope.fromArgs(args);
  final baselinePath = argValue(args, '--baseline') ?? _defaultBaselinePath;
  final baseline = _Baseline.load(baselinePath);

  final dartPackages = _findDartPackages();
  final dartFiles = scope
      .policyFiles()
      .where(
        (p) =>
            p.endsWith('.dart') &&
            (p.startsWith('apps/') || p.startsWith('packages/')),
      )
      .toList();
  final runtimeDart = scope
      .runtimeFiles(extensions: {'.dart'})
      .where((p) => !p.endsWith('.g.dart') && !p.endsWith('.freezed.dart'))
      .toList();
  final runtimeRust = scope.runtimeFiles(extensions: {'.rs'});

  final violations = <_Violation>[];
  violations.addAll(_checkDartDirection(dartPackages, dartFiles));
  violations.addAll(_checkRustDirection());
  violations.addAll(_checkCoreBarrels(dartFiles));
  violations.addAll(_checkAppShared(dartFiles));

  final backendSites = _backendClassSites(runtimeDart);
  final srcImportSites = _srcImportSites(dartPackages, dartFiles);
  final dispatchSites = [
    ..._dartDispatchSites(runtimeDart),
    ..._rustDispatchSites(runtimeRust),
  ];
  final coreLayerSites = _coreLayerSites(runtimeDart);

  final counted = {
    _Rule.backendClass: backendSites,
    _Rule.srcImport: srcImportSites,
    _Rule.nodeDispatch: dispatchSites,
    _Rule.coreLayers: coreLayerSites,
  };
  final current = <_Rule, Map<String, int>>{};
  for (final MapEntry(key: rule, value: sites) in counted.entries) {
    final byKey = <String, List<_Site>>{};
    for (final site in sites) {
      byKey.putIfAbsent(site.key, () => []).add(site);
    }
    current[rule] = {for (final e in byKey.entries) e.key: e.value.length};
    for (final MapEntry(key: key, value: list) in byKey.entries) {
      final allowed = baseline.count(rule, key);
      if (list.length <= allowed) continue;
      for (final site in list) {
        violations.add(
          _Violation(
            rule,
            site.location,
            '${site.what}${allowed > 0 ? ' (baseline allows $allowed under "$key", found ${list.length})' : ''}',
            rule.instead,
          ),
        );
      }
    }
  }

  if (args.contains('--list-sites')) {
    stdout.writeln(
      const JsonEncoder.withIndent('  ').convert({
        for (final rule in _Rule.counted)
          rule.id: {for (final site in counted[rule]!) site.location: site.key},
      }),
    );
    return;
  }

  final prunable = <String>[];
  for (final rule in _Rule.counted) {
    for (final MapEntry(key: key, value: allowed)
        in baseline.counts(rule).entries) {
      final now = current[rule]![key] ?? 0;
      if (now < allowed) {
        prunable.add('${rule.id}: "$key" allows $allowed, the tree has $now');
      }
    }
  }

  if (args.contains('--sync-baseline')) {
    baseline.shrinkTo(current);
    baseline.save(baselinePath);
    stdout.writeln('Baseline synced: $baselinePath');
  }

  stdout.writeln('Architecture rules audit');
  stdout.writeln(
    '  scanned ${dartFiles.length} Dart files, ${runtimeRust.length} Rust '
    'files, ${dartPackages.length} Dart packages, ${_rustCrates.length} '
    'Rust crates',
  );
  for (final rule in _Rule.counted) {
    final allowed = baseline.counts(rule).values.fold(0, (a, b) => a + b);
    stdout.writeln(
      '  ${rule.id}: ${counted[rule]!.length} site(s) in the tree, '
      '$allowed allowed by the baseline',
    );
  }
  if (prunable.isNotEmpty && !args.contains('--sync-baseline')) {
    stdout.writeln(
      'Baseline entries above what the tree has (run with --sync-baseline '
      'to lower them):',
    );
    for (final line in prunable) {
      stdout.writeln('  $line');
    }
  }

  if (violations.isEmpty) {
    stdout.writeln('Architecture rules audit passed.');
    return;
  }

  violations.sort((a, b) => a.location.compareTo(b.location));
  final byRule = <_Rule, List<_Violation>>{};
  for (final v in violations) {
    byRule.putIfAbsent(v.rule, () => []).add(v);
  }
  stderr.writeln(
    'Architecture rules audit FAILED: ${violations.length} '
    'violation(s).',
  );
  for (final MapEntry(key: rule, value: list) in byRule.entries) {
    stderr.writeln('');
    stderr.writeln('[${rule.id}] ${rule.summary}');
    final byHint = <String, List<_Violation>>{};
    for (final v in list) {
      byHint.putIfAbsent(v.instead, () => []).add(v);
    }
    for (final MapEntry(key: hint, value: group) in byHint.entries) {
      for (final v in group) {
        stderr.writeln('  ${v.location}: ${v.what}');
      }
      stderr.writeln('  Where it goes instead: $hint');
    }
  }
  exit(1);
}

enum _Rule {
  packageDirection(
    'package-direction',
    'A package uses only the packages below it.',
    '',
  ),
  backendClass(
    'backend-class',
    'Only the backend files name a backend class.',
    _backendInstead,
  ),
  srcImport(
    'src-import',
    'No file imports another package\'s src/ files.',
    _srcImportInstead,
  ),
  nodeDispatch(
    'node-dispatch',
    'Per-node-type facts live on the node table.',
    _dispatchInstead,
  ),
  coreLayers(
    'core-layers',
    'Core layers below providers/ do not import the provider layer.',
    _coreLayersInstead,
  ),
  coreBarrels(
    'core-barrels',
    'An import of skotiq_core names the layer it depends on.',
    _coreBarrelsInstead,
  ),
  appShared(
    'app-shared',
    'A shared folder of skotiq_app imports no screen.',
    _appSharedInstead,
  );

  const _Rule(this.id, this.summary, this.instead);

  final String id;
  final String summary;
  final String instead;

  static const counted = [backendClass, srcImport, nodeDispatch, coreLayers];
}

