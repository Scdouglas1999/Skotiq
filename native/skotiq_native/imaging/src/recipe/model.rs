// Canonical JSON + fingerprint
// ---------------------------------------------------------------------------

/// Render a JSON value with object keys sorted at every depth and no
/// insignificant whitespace.
///
/// Determinism depends on this: `serde_json::Map` iteration order follows the
/// crate's feature configuration, and a cache key built from unsorted keys makes
/// an identical recipe miss (or, with a hash, collide) depending on how the
/// value was constructed.
pub fn canonical_json(value: &Value) -> String {
    let mut out = String::new();
    write_canonical(value, &mut out);
    out
}

fn write_canonical(value: &Value, out: &mut String) {
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(true) => out.push_str("true"),
        Value::Bool(false) => out.push_str("false"),
        Value::Number(n) => out.push_str(&n.to_string()),
        Value::String(s) => write_json_string(s, out),
        Value::Array(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_canonical(item, out);
            }
            out.push(']');
        }
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort_unstable();
            out.push('{');
            for (i, key) in keys.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_json_string(key, out);
                out.push(':');
                if let Some(v) = map.get(key.as_str()) {
                    write_canonical(v, out);
                }
            }
            out.push('}');
        }
    }
}

fn write_json_string(s: &str, out: &mut String) {
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                out.push_str(&format!("\\u{:04x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

const FNV_OFFSET_128: u128 = 0x6c62_272e_07bb_0142_62b8_2175_6295_c58d;
const FNV_PRIME_128: u128 = 0x0000_0000_0100_0000_0000_0000_0000_013b;

/// A 128-bit FNV-1a digest of `bytes`, rendered as 32 lowercase hex digits.
///
/// Used for display and provenance (`HISTORY` cards, log lines). The render
/// cache keys on the canonical string itself, never on this digest, so a digest
/// collision can never serve the wrong cached image.
pub fn fingerprint_hex(bytes: &[u8]) -> String {
    let mut hash = FNV_OFFSET_128;
    for &b in bytes {
        hash ^= b as u128;
        hash = hash.wrapping_mul(FNV_PRIME_128);
    }
    format!("{hash:032x}")
}

