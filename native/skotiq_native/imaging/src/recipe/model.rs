/// The only recipe schema version this build reads and writes.
pub const RECIPE_SCHEMA_VERSION: u32 = 1;

/// The pixel budget between cancel polls inside an operation's inner loops.
///
/// An operation that walks more than this many pixels without returning calls
/// [`OpContext::check_cancel`] at least once per this many pixels, so a dawn job
/// aborts at safing instead of running the shutdown budget out.
pub const CANCEL_POLL_PIXELS: usize = 65_536;

