/// Faults an operation reports to the engine. Every variant names the caller
/// mistake or the missing capability; none of them describe a degraded result
/// that was applied anyway.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum OpError {
    /// The parameter payload is not a JSON object.
    #[error("{op_id}@{op_version}: parameters must be a JSON object, found {found}")]
    ParamsNotObject {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// JSON type of what was supplied.
        found: &'static str,
    },
    /// A parameter key the operation version does not define.
    #[error("{op_id}@{op_version}: unknown parameter '{key}'")]
    UnknownParam {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// The offending key.
        key: String,
    },
    /// A parameter with no default was not supplied.
    #[error("{op_id}@{op_version}: missing required parameter '{key}'")]
    MissingParam {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// The missing key.
        key: String,
    },
    /// A parameter has the wrong JSON type.
    #[error("{op_id}@{op_version}: parameter '{key}' must be {expected}, found {found}")]
    ParamType {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// The offending key.
        key: String,
        /// The type the operation requires.
        expected: &'static str,
        /// The type that was supplied.
        found: &'static str,
    },
    /// A parameter is outside the range the operation accepts.
    #[error("{op_id}@{op_version}: parameter '{key}' = {value} is outside {range}")]
    ParamRange {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// The offending key.
        key: String,
        /// The rejected value, rendered.
        value: String,
        /// The accepted range, rendered.
        range: String,
    },
    /// The image has zero width, height, or channels, or carries no pixels.
    #[error("image is empty (zero width/height/channels or no pixel data)")]
    EmptyImage,
    /// The declared geometry and the pixel buffer disagree.
    #[error("pixel buffer holds {found} samples, {width}x{height}x{channels} needs {expected}")]
    GeometryMismatch {
        /// Image width in pixels.
        width: u32,
        /// Image height in pixels.
        height: u32,
        /// Channel count.
        channels: u32,
        /// Samples the geometry requires.
        expected: usize,
        /// Samples the buffer holds.
        found: usize,
    },
    /// The source buffer's pixel type has no defined linear reading.
    #[error(
        "unsupported pixel type {found:?} for the recipe engine; linear masters are F32 and U16 is carried as ADU"
    )]
    UnsupportedPixelType {
        /// The pixel type that was supplied.
        found: PixelType,
    },
    /// The operation does not define a result for this channel layout.
    #[error(
        "{op_id}@{op_version}: unsupported channel layout: a {channels}-channel image, {expected}"
    )]
    UnsupportedChannels {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// Channel count supplied.
        channels: u32,
        /// What the operation requires, in words.
        expected: &'static str,
    },
    /// A capability the operation needs is absent on this install. The engine
    /// records the step as explicitly skipped with this reason and passes the
    /// image through unchanged; it never reports the step as applied.
    #[error("{op_id}@{op_version}: unavailable: {reason}")]
    Unavailable {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// Why the capability is absent, in the words the user reads.
        reason: String,
    },
    /// The cancel flag was raised while the operation was running.
    #[error("cancelled")]
    Cancelled,
    /// The operation ran and failed for a reason of its own.
    #[error("{op_id}@{op_version}: {reason}")]
    Failed {
        /// Operation id.
        op_id: &'static str,
        /// Operation version.
        op_version: u32,
        /// The underlying failure, already user-readable.
        reason: String,
    },
}

/// Faults the recipe engine reports for a recipe, independent of any one
/// operation's own failures.
///
/// **Every `index` field is the 0-based position in the step list; every
/// SENTENCE these errors print counts from 1.** The two are deliberately
/// different. The index is what code indexes with — `steps.remove(index)`,
/// the per-step verdict join — so it stays the list's own offset. The
/// sentence is read by the operator, beside an editor whose every other
/// number is 1-based: the step cards count "1 of 4", the export sheet writes
/// `step4-stretch` into the exported filename. A refusal that called that
/// same step "step 3" made the screen contradict itself, so the Display impls
/// add the one everywhere and nothing else moves.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum RecipeError {
    /// The recipe JSON does not decode.
    #[error("recipe decode failed: {0}")]
    Decode(String),
    /// The recipe does not encode.
    #[error("recipe encode failed: {0}")]
    Encode(String),
    /// The recipe was written by a schema this build does not read.
    #[error(
        "unsupported recipe schema version {found}; this build reads version {RECIPE_SCHEMA_VERSION}"
    )]
    UnsupportedSchemaVersion {
        /// Schema version found in the payload.
        found: u32,
    },
    /// No operation is registered under this id and version.
    #[error("step {}: no operation registered as {op_id}@{op_version}", .index + 1)]
    UnknownOp {
        /// Step index in the recipe, counted from 0; the sentence counts it
        /// from 1.
        index: usize,
        /// Operation id requested.
        op_id: String,
        /// Operation version requested.
        op_version: u32,
    },
    /// The step's parameters failed the operation's own validation.
    #[error("step {} ({op_id}@{op_version}) has invalid parameters: {source}", .index + 1)]
    InvalidParams {
        /// Step index in the recipe, counted from 0; the sentence counts it
        /// from 1.
        index: usize,
        /// Operation id.
        op_id: String,
        /// Operation version.
        op_version: u32,
        /// The operation's parameter fault.
        source: Box<OpError>,
    },
    /// A linear-stage operation sits after a stretched-stage operation.
    #[error(
        "step {} ({op_id}@{op_version}) is a linear-stage operation but step {} ({blocking_op_id}) already left the linear stage",
        .index + 1,
        .blocking_index + 1
    )]
    StageOrder {
        /// Index of the misplaced linear-stage step, counted from 0; the
        /// sentence counts it from 1.
        index: usize,
        /// Operation id of the misplaced step.
        op_id: String,
        /// Operation version of the misplaced step.
        op_version: u32,
        /// Index of the earliest stretched-stage step, counted from 0; the
        /// sentence counts it from 1.
        blocking_index: usize,
        /// Operation id of that step.
        blocking_op_id: String,
    },
    /// The branch link points past the end of the step list, or at itself.
    #[error("invalid parent link: {reason}")]
    InvalidParent {
        /// What is wrong with the link.
        reason: String,
    },
    /// A render was asked to stop after a step the recipe does not have.
    #[error("step {} is out of range; the recipe's step count is {step_count}", .index + 1)]
    StepIndexOutOfRange {
        /// The index that was requested, counted from 0; the sentence counts
        /// it from 1.
        index: usize,
        /// Number of steps in the recipe.
        step_count: usize,
    },
    /// A preview was asked for a pyramid level that was not built.
    #[error("pyramid level {level} is out of range; the pyramid's level count is {level_count}")]
    LevelOutOfRange {
        /// The level that was requested.
        level: u32,
        /// Number of levels the pyramid holds.
        level_count: u32,
    },
    /// The base image is not usable as a render input.
    #[error("base image is not renderable: {source}")]
    BaseImage {
        /// The image fault.
        source: Box<OpError>,
    },
    /// An operation failed while the recipe was rendering.
    #[error("step {} failed: {source}", .index + 1)]
    Step {
        /// Step index in the recipe, counted from 0; the sentence counts it
        /// from 1.
        index: usize,
        /// The operation's fault.
        source: Box<OpError>,
    },
    /// The cancel flag was raised during the render.
    #[error("cancelled")]
    Cancelled,
}

