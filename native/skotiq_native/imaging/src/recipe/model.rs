// OpContext
// ---------------------------------------------------------------------------

/// Everything an operation needs beyond its image and parameters.
///
/// The context is read-only to an operation: it carries handles and the render's
/// scale, never a channel back to the engine. Two renders of the same recipe
/// with equivalent contexts produce identical pixels.
#[derive(Clone)]
pub struct OpContext {
    cancel: Arc<AtomicBool>,
    catalog: Option<Arc<dyn PhotometryCatalog>>,
    wcs: Option<SipWcs>,
    level: u32,
}

impl Default for OpContext {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Debug for OpContext {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("OpContext")
            .field("cancel_requested", &self.cancel_requested())
            .field("catalog", &self.catalog.is_some())
            .field("wcs", &self.wcs.is_some())
            .field("level", &self.level)
            .finish()
    }
}

impl OpContext {
    /// A context with no cancel raised, no catalogue, no plate solve, at full
    /// resolution.
    pub fn new() -> Self {
        Self {
            cancel: Arc::new(AtomicBool::new(false)),
            catalog: None,
            wcs: None,
            level: 0,
        }
    }

    /// Share an externally owned cancel flag. The owner raises it at safing; the
    /// engine and every operation poll it.
    pub fn with_cancel(mut self, cancel: Arc<AtomicBool>) -> Self {
        self.cancel = cancel;
        self
    }

    /// Attach a photometric catalogue. Operations that need one and find none
    /// return [`OpError::Unavailable`], which the engine records as an explicit
    /// skip.
    pub fn with_catalog(mut self, catalog: Arc<dyn PhotometryCatalog>) -> Self {
        self.catalog = Some(catalog);
        self
    }

    /// Attach the base master's plate solve. Absent when the master carries no
    /// astrometry.
    pub fn with_wcs(mut self, wcs: SipWcs) -> Self {
        self.wcs = Some(wcs);
        self
    }

    /// The pyramid level this render runs at.
    pub fn at_level(mut self, level: u32) -> Self {
        self.level = level;
        self
    }

    /// The shared cancel flag, for handing to a nested worker.
    pub fn cancel_flag(&self) -> Arc<AtomicBool> {
        Arc::clone(&self.cancel)
    }

    /// Whether cancellation has been requested.
    pub fn cancel_requested(&self) -> bool {
        self.cancel.load(Ordering::Relaxed)
    }

    /// Raise the cancel flag.
    pub fn request_cancel(&self) {
        self.cancel.store(true, Ordering::Relaxed);
    }

    /// `Err(OpError::Cancelled)` once cancellation has been requested. Called at
    /// least once per [`CANCEL_POLL_PIXELS`] pixels inside a long loop.
    pub fn check_cancel(&self) -> Result<(), OpError> {
        if self.cancel_requested() {
            Err(OpError::Cancelled)
        } else {
            Ok(())
        }
    }

    /// The photometric catalogue, if one is attached.
    pub fn catalog(&self) -> Option<&Arc<dyn PhotometryCatalog>> {
        self.catalog.as_ref()
    }

    /// The base master's astrometry, if it is known.
    pub fn wcs(&self) -> Option<&SipWcs> {
        self.wcs.as_ref()
    }

    /// The pyramid level: `0` is full resolution, `n` is a `2^n` downsample.
    pub fn level(&self) -> u32 {
        self.level
    }

    /// Linear size of a rendered pixel relative to the base master: `1 / 2^level`.
    /// An operation whose parameters are in pixels (radii, kernel widths, sample
    /// grid spacing) multiplies them by this so a preview looks like the full
    /// render.
    pub fn scale(&self) -> f64 {
        1.0 / (1u64 << self.level.min(63)) as f64
    }

    /// The parts of the context that can reach a pixel value, as a stable
    /// string. The render cache carries it, so changing the plate solve, the
    /// pyramid level, or the photometry invalidates the boundaries that
    /// depended on it.
    ///
    /// A catalogue contributes [`PhotometryCatalog::identity`], not merely its
    /// presence: a handle whose stars changed keys differently, so no caller has
    /// to clear the cache to keep one star list's colours out of another's
    /// render.
    pub fn identity(&self) -> String {
        let mut out = match &self.catalog {
            None => format!("L{}|cat:0", self.level),
            Some(catalog) => format!("L{}|cat:1:{}", self.level, catalog.identity()),
        };
        match &self.wcs {
            None => out.push_str("|wcs:0"),
            Some(w) => {
                let full = format!(
                    "{},{},{},{},{},{},{},{},{},{},{},{},{:?},{:?},{:?},{:?}",
                    w.crval1,
                    w.crval2,
                    w.crpix1,
                    w.crpix2,
                    w.cd1_1,
                    w.cd1_2,
                    w.cd2_1,
                    w.cd2_2,
                    w.a_order,
                    w.b_order,
                    w.ap_order,
                    w.bp_order,
                    w.a_coeffs,
                    w.b_coeffs,
                    w.ap_coeffs,
                    w.bp_coeffs,
                );
                out.push_str(&format!("|wcs:1:{}", fingerprint_hex(full.as_bytes())));
            }
        }
        out
    }
}

