/// Who authored a recipe. The morning draft is `autopilot` until the user edits
/// it; the distinction drives "this is a first draft" affordances in the editor.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum RecipeAuthor {
    /// Generated by the dawn autopilot.
    Autopilot,
    /// Created or last authored by the user.
    User,
}

impl RecipeAuthor {
    /// The `camelCase` wire token.
    pub fn as_wire(&self) -> &'static str {
        match self {
            RecipeAuthor::Autopilot => "autopilot",
            RecipeAuthor::User => "user",
        }
    }
}

/// The branch link: a recipe derived from another one, diverging after
/// `divergence_index` steps.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct RecipeParent {
    /// Id of the recipe this one branched from.
    pub recipe_id: String,
    /// Number of leading steps shared with the parent. `0` means the branch
    /// diverges immediately; `steps.len()` means it is a pure extension.
    pub divergence_index: usize,
}

/// One operation invocation in a recipe.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct RecipeStep {
    /// Registry id of the operation (`background_extract`, `stretch`, ...).
    pub op_id: String,
    /// Registry version of the operation. A recipe keeps rendering with the
    /// version it was written with.
    pub op_version: u32,
    /// Operation parameters, validated by the operation's own
    /// [`DarkroomOp::validate_params`]. Carried opaquely so a recipe written by
    /// a newer op version round-trips through an older reader unchanged.
    #[serde(default = "empty_params")]
    pub params: Value,
    /// `false` renders as if the step were absent; the step and its parameters
    /// survive so the toggle is non-destructive.
    pub enabled: bool,
}

fn empty_params() -> Value {
    Value::Object(Map::new())
}

impl RecipeStep {
    /// A step with an empty parameter object, enabled.
    pub fn new(op_id: impl Into<String>, op_version: u32) -> Self {
        Self {
            op_id: op_id.into(),
            op_version,
            params: empty_params(),
            enabled: true,
        }
    }

    /// The same step with the given parameters.
    pub fn with_params(mut self, params: Value) -> Self {
        self.params = params;
        self
    }

    /// The same step with the given enablement.
    pub fn with_enabled(mut self, enabled: bool) -> Self {
        self.enabled = enabled;
        self
    }
}

/// A non-destructive edit stack over one linear master.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Recipe {
    /// Stable identity of this recipe (the database row id).
    pub id: String,
    /// Wire schema version; see [`RECIPE_SCHEMA_VERSION`].
    pub schema_version: u32,
    /// Identifies the base master's pixels. Two bases that render differently
    /// have different refs — the render cache keys on this string, so reusing a
    /// ref for different pixels serves the wrong image.
    pub base_master_ref: String,
    /// Author of the current step list.
    pub created_by: RecipeAuthor,
    /// Branch link, absent for a root recipe.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent: Option<RecipeParent>,
    /// Operations in application order.
    #[serde(default)]
    pub steps: Vec<RecipeStep>,
}

impl Recipe {
    /// A root recipe with no steps at the current schema version.
    pub fn new(
        id: impl Into<String>,
        base_master_ref: impl Into<String>,
        created_by: RecipeAuthor,
    ) -> Self {
        Self {
            id: id.into(),
            schema_version: RECIPE_SCHEMA_VERSION,
            base_master_ref: base_master_ref.into(),
            created_by,
            parent: None,
            steps: Vec::new(),
        }
    }

    /// Decode a recipe from its wire JSON.
    ///
    /// The schema version is read before the struct is decoded, so a recipe
    /// from a future build reports [`RecipeError::UnsupportedSchemaVersion`]
    /// rather than an unknown-field message.
    ///
    /// The payload is checked for being an object first, and each failure is
    /// named for itself. Reading `schemaVersion` off a [`Value`] answers `None`
    /// for an array, a string, a number, a boolean and `null` alike — none of
    /// which has fields at all — so every one of them was reported as a recipe
    /// missing that field, which is not what the caller sent. A `schemaVersion`
    /// that is present but is not a whole number is likewise stated as the
    /// wrong type rather than as an absence.
    pub fn from_json(json: &str) -> Result<Self, RecipeError> {
        let value: Value =
            serde_json::from_str(json).map_err(|e| RecipeError::Decode(e.to_string()))?;
        let Value::Object(fields) = &value else {
            return Err(RecipeError::Decode(format!(
                "a recipe is a JSON object; this payload is {}",
                super::params::type_name(&value)
            )));
        };
        let stated = fields
            .get("schemaVersion")
            .ok_or_else(|| RecipeError::Decode("recipe is missing schemaVersion".to_string()))?;
        let found = stated.as_u64().ok_or_else(|| {
            RecipeError::Decode(format!(
                "recipe schemaVersion must be a whole number; this one states {stated}"
            ))
        })?;
        let found = u32::try_from(found)
            .map_err(|_| RecipeError::UnsupportedSchemaVersion { found: u32::MAX })?;
        if found != RECIPE_SCHEMA_VERSION {
            return Err(RecipeError::UnsupportedSchemaVersion { found });
        }
        serde_json::from_value(value).map_err(|e| RecipeError::Decode(e.to_string()))
    }

    /// Encode a recipe to its wire JSON.
    pub fn to_json(&self) -> Result<String, RecipeError> {
        serde_json::to_string(self).map_err(|e| RecipeError::Encode(e.to_string()))
    }

    /// The canonical form of the step prefix `0..=upto`, restricted to enabled
    /// steps: the string the render cache and the provenance fingerprint agree
    /// on. Object keys are sorted at every depth, so two logically equal
    /// parameter objects always produce the same bytes.
    pub fn canonical_prefix(&self, upto: usize) -> String {
        let end = upto.min(self.steps.len().saturating_sub(1));
        let mut out = String::from("[");
        let mut first = true;
        if !self.steps.is_empty() {
            for step in self.steps.iter().take(end + 1).filter(|s| s.enabled) {
                if !first {
                    out.push(',');
                }
                first = false;
                out.push_str(&canonical_json(&serde_json::json!({
                    "opId": step.op_id,
                    "opVersion": step.op_version,
                    "params": step.params,
                })));
            }
        }
        out.push(']');
        out
    }

    /// Index of the last step, or `None` for an empty recipe.
    pub fn last_index(&self) -> Option<usize> {
        self.steps.len().checked_sub(1)
    }
}

