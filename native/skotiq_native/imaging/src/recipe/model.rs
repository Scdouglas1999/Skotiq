//! The recipe wire format, the image/context an operation sees, and the
//! [`DarkroomOp`] trait every operation implements.
//!
//! A recipe is *data*: an ordered list of `{opId, opVersion, params, enabled}`
//! records over a named base master. Rendering it replays the operations; the
//! recipe itself never holds pixels, so nothing interpretive is baked into a
//! file the user can lose work in.
//!
//! # Wire format
//!
//! JSON, `camelCase`, versioned by [`RECIPE_SCHEMA_VERSION`]. The same bytes are
//! stored in the Dart-side database, written as a `.nsrecipe` sidecar, and
//! embedded in FITS `HISTORY` cards, so field names are a contract: renaming one
//! breaks recipes already on disk.
//!
//! # Determinism
//!
//! For a fixed `(op_id, op_version, params, input pixels)` an operation produces
//! byte-identical output. That forbids clock reads, randomness without a
//! recipe-carried seed, and any iteration over an unordered collection that
//! reaches pixel values. Improving an algorithm ships a new version and leaves
//! the old one registered.

use std::collections::BTreeMap;
use std::fmt;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};

