/// One catalogue star with genuine photometry, in degrees.
///
/// `b_minus_v` is a catalogue measurement. A value derived from the frame's own
/// instrumental magnitude makes the colour fit circular and is never supplied
/// here; a star without a real `B − V` is left out of the result.
#[derive(Debug, Clone, PartialEq)]
pub struct CatalogStar {
    /// Right ascension in degrees.
    pub ra_deg: f64,
    /// Declination in degrees.
    pub dec_deg: f64,
    /// Johnson V magnitude.
    pub v_mag: f64,
    /// Johnson `B − V` colour index.
    pub b_minus_v: f64,
}

/// Faults a photometric catalogue reports.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum CatalogError {
    /// No catalogue data covers this field on this install.
    #[error("photometric catalog unavailable: {reason}")]
    Unavailable {
        /// Why no catalogue is usable, in the words the user reads.
        reason: String,
    },
    /// The catalogue was reachable and the query failed.
    #[error("photometric catalog query failed: {reason}")]
    QueryFailed {
        /// The underlying failure.
        reason: String,
    },
}

/// The photometry source an operation queries.
///
/// The shipped photometry is Johnson B and V (HYG `ci`, APASS DR9); there is no
/// Gaia BP/RP and no filter-transmission database, so an implementation returns
/// `B − V` only.
pub trait PhotometryCatalog: Send + Sync {
    /// Stars with genuine `B − V` inside `radius_deg` of `(ra_deg, dec_deg)`,
    /// down to `mag_limit` in V.
    ///
    /// The order of the returned stars is part of the determinism contract: an
    /// implementation returns them in a stable order for a fixed query.
    fn cone_search(
        &self,
        ra_deg: f64,
        dec_deg: f64,
        radius_deg: f64,
        mag_limit: f64,
    ) -> Result<Vec<CatalogStar>, CatalogError>;

    /// A short, stable digest of the star data this catalogue answers from.
    ///
    /// [`OpContext::identity`] carries it into the render cache key verbatim, so
    /// two catalogues whose answers differ key differently and neither can be
    /// served a boundary the other produced. Two handles that would answer every
    /// query alike return the same string; anything that can reach a pixel —
    /// a star added, a magnitude corrected, a colour index revised — changes it.
    ///
    /// It is a digest rather than the data itself because the key is stored as a
    /// string: an implementation over a million stars returns a fingerprint of
    /// them, not the list.
    fn identity(&self) -> String;
}

