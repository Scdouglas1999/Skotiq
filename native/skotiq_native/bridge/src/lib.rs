/// Global Tokio runtime for async operations.
///
/// Wrapped in `Option` so the `OnceLock` closure can record an init failure
/// (storing `None`) instead of having to construct the runtime BEFORE calling
/// `get_or_init` — which would race losing threads into dropping a successfully-
/// built Runtime, which tokio refuses inside an async context (see
/// `ensure_runtime` for the full rationale).
static RUNTIME: OnceLock<Option<Runtime>> = OnceLock::new();

/// Tracks whether runtime initialization has permanently failed.
/// Once this is set to true, all async operations will return errors instead of attempting
/// to create a runtime (which would just fail again).
static RUNTIME_INIT_FAILED: AtomicBool = AtomicBool::new(false);

/// Error message from the last runtime initialization failure.
/// Used to provide consistent error messages when RUNTIME_INIT_FAILED is true.
static RUNTIME_ERROR_MSG: OnceLock<String> = OnceLock::new();

static LOG_DIR: OnceLock<PathBuf> = OnceLock::new();

/// Global log file guard (keeps file writer alive)
static LOG_GUARD: OnceLock<tracing_appender::non_blocking::WorkerGuard> = OnceLock::new();

/// Tracks whether the tracing subscriber has been initialized.
/// Prevents double-init when `init_native_internal` recurses on log directory failure.
static TRACING_INITIALIZED: AtomicBool = AtomicBool::new(false);

/// Initialize the global runtime, never panicking. If creation fails after all
/// fallback attempts the error is cached in a static and every later call returns
/// it without retrying, so a resource exhaustion is not hammered.
pub(crate) fn ensure_runtime() -> Result<&'static Runtime, SkotiqError> {
    // Construct lazily and atomically. The construction MUST happen inside
    // `OnceLock::get_or_init` so that losing threads block on the closure
    // and observe the winner's stored value — never building (and then
    // having to drop) a parallel Runtime of their own. Dropping a tokio
    // Runtime inside an async context panics with "Cannot drop a runtime in
    // a context where blocking is not allowed", which is exactly what
    // happened to parallel `#[tokio::test]` cases that called
    // `DeviceManager::new` (which calls `ensure_runtime`) — the loser of
    // the race dropped its newly-built Runtime in the test's async context.
    //
    // The closure stores `None` on failure so we can preserve the original
    // "never retry forever" semantics (RUNTIME_INIT_FAILED is set on the
    // first failure path below).
    let stored = RUNTIME.get_or_init(|| match try_create_runtime_with_fallbacks() {
        Ok(rt) => Some(rt),
        Err(error_msg) => {
            eprintln!(
                "FATAL: Runtime initialization failed permanently: {}",
                error_msg
            );
            tracing::error!("Runtime initialization failed permanently: {}", error_msg);
            let _ = RUNTIME_ERROR_MSG.set(error_msg);
            RUNTIME_INIT_FAILED.store(true, Ordering::Release);
            None
        }
    });

    match stored {
        Some(rt) => Ok(rt),
        None => {
            let msg = RUNTIME_ERROR_MSG
                .get()
                .map(|s| s.as_str())
                .unwrap_or("Unknown runtime initialization failure");
            Err(SkotiqError::RuntimeInitFailed(msg.to_string()))
        }
    }
}

/// Try to create a runtime with fallbacks. Returns the runtime or an error message.
/// This function NEVER panics.
fn try_create_runtime_with_fallbacks() -> Result<Runtime, String> {
    // First attempt: Create a multi-threaded runtime with default settings
    match Runtime::new() {
        Ok(rt) => {
            tracing::debug!("Created multi-threaded Tokio runtime");
            return Ok(rt);
        }
        Err(e) => {
            eprintln!("WARNING: Failed to create default Tokio runtime: {}", e);
            tracing::warn!("Failed to create default Tokio runtime: {}", e);
        }
    }

    // Second attempt: Try a current-thread runtime with all features
    match tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
    {
        Ok(rt) => {
            tracing::warn!("Using single-threaded Tokio runtime as fallback");
            return Ok(rt);
        }
        Err(e2) => {
            eprintln!(
                "WARNING: Single-threaded runtime with all features failed: {}",
                e2
            );
            tracing::warn!("Single-threaded runtime with all features failed: {}", e2);
        }
    }

    // Third attempt: Minimal runtime without IO or timers
    match tokio::runtime::Builder::new_current_thread().build() {
        Ok(rt) => {
            tracing::warn!("Using minimal Tokio runtime (no IO, no timers)");
            eprintln!("WARNING: Using minimal Tokio runtime - some features may not work");
            return Ok(rt);
        }
        Err(e3) => {
            let error_msg = format!(
                "All runtime creation attempts failed. System may be resource-exhausted: {}",
                e3
            );
            eprintln!("CRITICAL: {}", error_msg);
            Err(error_msg)
        }
    }
}

/// Tracks whether the panic handler has been installed.
/// Used to prevent installing the panic hook multiple times.
static PANIC_HANDLER_INSTALLED: AtomicBool = AtomicBool::new(false);

/// Initialize panic handler to catch panics and log them.
/// This function is idempotent - repeated calls are ignored after the first.
fn init_panic_handler() {
    // Use compare_exchange to ensure we only install the handler once
    if PANIC_HANDLER_INSTALLED
        .compare_exchange(false, true, Ordering::SeqCst, Ordering::SeqCst)
        .is_ok()
    {
        panic::set_hook(Box::new(|panic_info| {
            let msg = panic_info.to_string();
            let location = panic_info
                .location()
                .map(|l| format!("{}:{}:{}", l.file(), l.line(), l.column()))
                .unwrap_or_else(|| "unknown".to_string());

            eprintln!("PANIC at {}: {}", location, msg);
            tracing::error!("PANIC at {}: {}", location, msg);
        }));
    }
}

/// Initialize the native bridge with logging. Called once at app startup, with
/// `log_directory` naming where log files go (`None` logs to console only).
///
/// All initialization runs under panic catching, so a catastrophic failure
/// returns an error instead of crashing the Flutter app.
#[flutter_rust_bridge::frb(sync)]
pub fn init_native_with_logging(log_directory: Option<String>) -> Result<(), SkotiqError> {
    // Install panic handler first - this must happen before any other code
    // so that panics are properly logged even if catch_unwind doesn't catch them
    init_panic_handler();

    // Wrap the entire initialization in panic catching for FFI safety
    catch_panic_sync(|| init_native_internal(log_directory))
}

/// Internal initialization function that does the actual work.
/// Separated out so we can wrap it in panic catching.
fn init_native_internal(log_directory: Option<String>) -> Result<(), SkotiqError> {
    // Guard against double-initialization of the tracing subscriber.
    // This can happen when the recursive fallback path (log dir creation failure)
    // calls init_native_internal(None), which would attempt a second .init().
    if TRACING_INITIALIZED.swap(true, Ordering::SeqCst) {
        // Already initialized - just ensure runtime exists and return
        ensure_runtime()?;
        return Ok(());
    }

    use tracing_subscriber::fmt;
    use tracing_subscriber::EnvFilter;
    use tracing_subscriber::Layer;

    // Console shows INFO+ only (keeps output clean for users).
    // File gets DEBUG+ for diagnostics.
    // RUST_LOG env var overrides both for developers.
    //
    // Special-cased filters: `wgpu_core`/`wgpu_hal` emit a per-frame
    // `Device::maintain: waiting for submission index N` at INFO level —
    // thousands per second once the planetarium renderer is hot. That spam
    // makes the console useless for diagnosing anything else, so we silence
    // those crates at INFO (`wgpu_core::device=warn`, `wgpu_hal=warn`)
    // unless the operator explicitly bumps them via RUST_LOG.
    const DEFAULT_FILTER: &str = "info,wgpu_core=warn,wgpu_hal=warn,wgpu=warn,naga=warn";
    let console_filter =
        EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new(DEFAULT_FILTER));
    let file_filter = EnvFilter::new(format!("debug,{DEFAULT_FILTER}"));

    if let Some(log_dir) = log_directory {
        // Store log directory for later access
        let log_path = PathBuf::from(&log_dir);

        // Create log directory if it doesn't exist
        if let Err(e) = std::fs::create_dir_all(&log_path) {
            eprintln!("Failed to create log directory: {}", e);
            // Fall back to console-only logging.
            // Reset TRACING_INITIALIZED so the recursive call can proceed with console-only init.
            TRACING_INITIALIZED.store(false, Ordering::SeqCst);
            return init_native_internal(None);
        }

        LOG_DIR.set(log_path.clone()).ok();

        let file_appender = tracing_appender::rolling::daily(&log_path, "skotiq.log");
        let (non_blocking, guard) = tracing_appender::non_blocking(file_appender);

        // Keep guard alive for the lifetime of the app
        LOG_GUARD.set(guard).ok();

        // Console: INFO+ (clean output for users)
        let console_layer = fmt::layer()
            .with_target(false)
            .with_ansi(true)
            .with_filter(console_filter);

        // File: DEBUG+ (full diagnostics for troubleshooting)
        let file_layer = fmt::layer()
            .with_target(true)
            .with_ansi(false)
            .with_writer(non_blocking)
            .with_filter(file_filter);

        tracing_subscriber::registry()
            .with(console_layer)
            .with(file_layer)
            .init();

        tracing::info!("Skotiq Native Bridge initialized with file logging");
        tracing::info!("Log directory: {}", log_dir);

        // Clean up old log files (keep last 7 days)
        cleanup_old_logs(&log_path, 7);
    } else {
        // Console-only logging (INFO+ for clean output)
        tracing_subscriber::fmt()
            .with_max_level(tracing::Level::INFO)
            .with_target(false)
            .init();

        tracing::info!("Skotiq Native Bridge initialized (console logging only)");
    }

    // Ensure runtime is created - propagate errors to caller
    ensure_runtime()?;

    // Start the process-wide ASCOM STA worker so the single persistent
    // apartment + message pump exists before any device connects. Idempotent
    // (OnceLock-guarded); headless has no Flutter event loop to provide a pump,
    // which is the root cause of the unattended-ASCOM beta-gap bugs.
    #[cfg(windows)]
    crate::ascom_wrapper::sta_worker::ensure_sta_worker();

    Ok(())
}

/// Get the current log directory path
#[flutter_rust_bridge::frb(sync)]
pub fn get_log_directory() -> Option<String> {
    LOG_DIR.get().map(|p| p.to_string_lossy().to_string())
}

/// Get the current log file path (today's log)
#[flutter_rust_bridge::frb(sync)]
pub fn get_current_log_file() -> Option<String> {
    LOG_DIR.get().map(|dir| {
        let today = chrono::Local::now().format("%Y-%m-%d");
        dir.join(format!("skotiq.log.{}", today))
            .to_string_lossy()
            .to_string()
    })
}

/// Clean up old log files, keeping only the most recent N days
fn cleanup_old_logs(log_dir: &PathBuf, keep_days: i64) {
    use chrono::TimeZone;

    let cutoff = chrono::Local::now() - chrono::Duration::days(keep_days);

    let entries = match std::fs::read_dir(log_dir) {
        Ok(entries) => entries,
        Err(e) => {
            tracing::debug!("Cannot read log directory for cleanup: {}", e);
            return;
        }
    };

    for entry in entries.filter_map(|e| e.ok()) {
        let path = entry.path();
        let name = match path.file_name().and_then(|n| n.to_str()) {
            Some(name) => name,
            None => continue,
        };

        // Parse date from filename like "skotiq.log.2024-01-15"
        if !name.starts_with("skotiq.log.") {
            continue;
        }

        let date_str = match name.strip_prefix("skotiq.log.") {
            Some(s) => s,
            None => continue,
        };

        let file_date = match chrono::NaiveDate::parse_from_str(date_str, "%Y-%m-%d") {
            Ok(date) => date,
            Err(_) => continue, // Skip files with invalid date format
        };

        // Safely create datetime - if None, skip this file
        let file_datetime = match file_date.and_hms_opt(0, 0, 0) {
            Some(dt) => dt,
            None => {
                tracing::debug!("Invalid time components for date {}", date_str);
                continue;
            }
        };

        let file_local = match chrono::Local.from_local_datetime(&file_datetime).single() {
            Some(local) => local,
            None => continue, // Ambiguous or invalid local time
        };

        if file_local < cutoff {
            if let Err(e) = std::fs::remove_file(&path) {
                tracing::warn!("Failed to delete old log file {:?}: {}", path, e);
            } else {
                tracing::debug!("Deleted old log file: {:?}", path);
            }
        }
    }
}

// FFI boundary panic safety

/// Run a synchronous operation with panic catching: a panic becomes
/// `SkotiqError::Internal` rather than unwinding across the FFI boundary,
/// which would be undefined behavior.
pub(crate) fn catch_panic_sync<F, T>(f: F) -> Result<T, SkotiqError>
where
    F: FnOnce() -> Result<T, SkotiqError> + panic::UnwindSafe,
{
    match panic::catch_unwind(f) {
        Ok(result) => result,
        Err(panic_payload) => {
            let panic_msg = extract_panic_message(&panic_payload);
            tracing::error!("Panic caught at FFI boundary: {}", panic_msg);
            Err(SkotiqError::Internal(format!(
                "Internal panic: {}",
                panic_msg
            )))
        }
    }
}

/// Extract a human-readable message from a panic payload.
///
/// Panic payloads can be different types (`&str`, `String`, or other types).
/// This function attempts to extract the most useful message.
fn extract_panic_message(payload: &Box<dyn std::any::Any + Send>) -> String {
    if let Some(s) = payload.downcast_ref::<&str>() {
        (*s).to_string()
    } else if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else {
        "Unknown panic".to_string()
    }
}

/// The global runtime, or `SkotiqError::RuntimeInitFailed` if it cannot be
/// created. An alias for [`ensure_runtime`]; it never panics.
pub(crate) fn get_runtime() -> Result<&'static Runtime, SkotiqError> {
    ensure_runtime()
}
